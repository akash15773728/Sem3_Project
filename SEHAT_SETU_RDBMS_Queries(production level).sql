-- ----------------------------------------------------------------------------
-- QUERY 6: Explicit Transaction Demonstration (Demonstrating COMMIT & ROLLBACK)
-- Scenario A: Successful Commit of Facility Capacity Update
-- ----------------------------------------------------------------------------
BEGIN TRANSACTION;
    BEGIN TRY
        UPDATE dbo.facility_capacity
        SET specialist_count = 2,
            equipment_available = 1,
            last_updated = SYSUTCDATETIME()
        WHERE facility_id = 1 AND service_id = 1;

        INSERT INTO dbo.activity_logs (user_id, action)
        VALUES (1, 'Admin updated capacity for Facility 1 Service 1: Specialists increased to 2.');

        COMMIT TRANSACTION;
        PRINT 'Transaction Scenario A: Committed successfully.';
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        PRINT 'Transaction Scenario A: Rolled back due to error.';
    END CATCH;

-- ----------------------------------------------------------------------------
-- Scenario B: Intentional Rollback on Constraint Violation (Bed count negative)
-- ----------------------------------------------------------------------------
BEGIN TRANSACTION;
    BEGIN TRY
        -- This statement intentionally violates CHECK (beds_available >= 0)
        UPDATE dbo.facility_capacity
        SET beds_available = -5
        WHERE facility_id = 1 AND service_id = 1;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        -- Caught CHECK constraint violation, gracefully rollback
        ROLLBACK TRANSACTION;
        PRINT 'Transaction Scenario B: Rolled back successfully on constraint error: ' + ERROR_MESSAGE();
    END CATCH;

-- ----------------------------------------------------------------------------
-- QUERY 7: Service Demand Ranking (Identifies most frequently referred specialties)
-- ----------------------------------------------------------------------------
SELECT 
    s.service_name,
    s.category,
    COUNT(r.referral_id) AS total_requests,
    COUNT(DISTINCT r.source_facility_id) AS referring_facilities_count,
    SUM(CASE WHEN r.priority = 'Emergency' THEN 1 ELSE 0 END) AS emergency_count
FROM dbo.services s
LEFT JOIN dbo.referrals r ON s.service_id = r.service_id
GROUP BY s.service_name, s.category
ORDER BY total_requests DESC;
