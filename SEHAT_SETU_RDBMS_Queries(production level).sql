-- ----------------------------------------------------------------------------
-- QUERY 1: Multi-Table JOIN - Comprehensive Referral Audit
-- Joins 5 tables: referrals, source facility, destination facility, service, user
-- ----------------------------------------------------------------------------
SELECT 
    r.referral_id,
    r.referral_date,
    r.priority,
    r.status,
    src.facility_name AS source_facility,
    src_dist.district_name AS source_district,
    dst.facility_name AS destination_facility,
    dst_dist.district_name AS destination_district,
    s.service_name AS required_service,
    s.category AS service_category,
    u.name AS referred_by_staff,
    r.reason,
    r.notes
FROM dbo.referrals r
INNER JOIN dbo.facilities src ON r.source_facility_id = src.facility_id
INNER JOIN dbo.districts src_dist ON src.district_id = src_dist.district_id
INNER JOIN dbo.facilities dst ON r.destination_facility_id = dst.facility_id
INNER JOIN dbo.districts dst_dist ON dst.district_id = dst_dist.district_id
INNER JOIN dbo.services s ON r.service_id = s.service_id
INNER JOIN dbo.users u ON r.created_by = u.user_id
ORDER BY r.referral_date DESC, r.referral_id DESC;

-- ----------------------------------------------------------------------------
-- QUERY 2: Cross-District Referral Flow Matrix (Aggregation & GROUP BY)
-- Shows healthcare movement patterns between source and destination districts.
-- ----------------------------------------------------------------------------
SELECT 
    src_d.district_name AS originating_district,
    dst_d.district_name AS receiving_district,
    COUNT(r.referral_id) AS total_referrals,
    COUNT(CASE WHEN r.priority = 'Emergency' THEN 1 END) AS emergency_referrals,
    COUNT(CASE WHEN r.status = 'Completed' THEN 1 END) AS completed_referrals
FROM dbo.referrals r
INNER JOIN dbo.facilities src_f ON r.source_facility_id = src_f.facility_id
INNER JOIN dbo.districts src_d ON src_f.district_id = src_d.district_id
INNER JOIN dbo.facilities dst_f ON r.destination_facility_id = dst_f.facility_id
INNER JOIN dbo.districts dst_d ON dst_f.district_id = dst_d.district_id
GROUP BY src_d.district_name, dst_d.district_name
ORDER BY total_referrals DESC;

-- ----------------------------------------------------------------------------
-- QUERY 3: Potential Healthcare Gap Identification (Core Decision-Support Logic)
-- Compares reported facility capacity with outbound referral volume.
-- Flags facilities repeatedly referring patients for services they lack.
-- ----------------------------------------------------------------------------
SELECT 
    f.facility_name,
    d.district_name,
    s.service_name,
    s.category AS service_domain,
    ISNULL(fc.service_available, 0) AS service_reported_available,
    ISNULL(fc.specialist_count, 0) AS reported_specialists,
    ISNULL(fc.equipment_available, 0) AS reported_equipment,
    ISNULL(fc.beds_available, 0) AS reported_beds,
    COUNT(r.referral_id) AS outbound_referral_count,
    CASE 
        WHEN ISNULL(fc.service_available, 0) = 0 AND COUNT(r.referral_id) >= 3 
            THEN 'Potential Gap: Service Unavailable with Repeated Referrals'
        WHEN ISNULL(fc.specialist_count, 0) = 0 AND COUNT(r.referral_id) >= 2 
            THEN 'Needs Review: Zero Specialists Reported'
        WHEN ISNULL(fc.equipment_available, 0) = 0 AND COUNT(r.referral_id) >= 2 
            THEN 'Needs Review: Equipment Deficit Reported'
        WHEN fc.capacity_id IS NULL 
            THEN 'Insufficient Capacity Data: No Baseline Record Filed'
        ELSE 'Adequate / Normal Operational State'
    END AS gap_classification
FROM dbo.facilities f
INNER JOIN dbo.districts d ON f.district_id = d.district_id
CROSS JOIN dbo.services s
LEFT JOIN dbo.facility_capacity fc ON f.facility_id = fc.facility_id AND s.service_id = fc.service_id
LEFT JOIN dbo.referrals r ON f.facility_id = r.source_facility_id AND s.service_id = r.service_id
GROUP BY 
    f.facility_name, d.district_name, s.service_name, s.category,
    fc.capacity_id, fc.service_available, fc.specialist_count, fc.equipment_available, fc.beds_available
HAVING COUNT(r.referral_id) > 0 OR fc.service_available = 0
ORDER BY outbound_referral_count DESC;

